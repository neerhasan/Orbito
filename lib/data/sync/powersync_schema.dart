import 'package:powersync/powersync.dart';

/// The tables PowerSync keeps on the device. This must match the Drift tables
/// in `lib/data/local/app_database.dart` and the SQL in `supabase/`.
///
/// PowerSync adds the `id` column by itself, so it is not listed.
const powerSyncSchema = Schema([
  Table('sync_test', [
    Column.text('user_id'),
    Column.text('text'),
    Column.text('created_at'),
    Column.text('updated_at'),
    Column.text('deleted_at'),
  ]),
  Table('life_areas', [
    Column.text('user_id'),
    Column.text('name'),
    Column.text('color'),
    Column.text('icon'),
    Column.text('created_at'),
    Column.text('updated_at'),
    Column.text('deleted_at'),
  ]),
  Table('goals', [
    Column.text('user_id'),
    Column.text('title'),
    Column.text('life_area_id'),
    Column.text('target_date'),
    Column.text('done_when'),
    Column.integer('progress'),
    Column.text('color'),
    Column.text('icon'),
    Column.text('created_at'),
    Column.text('updated_at'),
    Column.text('deleted_at'),
  ]),
  Table('projects', [
    Column.text('user_id'),
    Column.text('name'),
    Column.text('goal_id'),
    Column.text('color'),
    Column.text('icon'),
    Column.text('created_at'),
    Column.text('updated_at'),
    Column.text('deleted_at'),
  ]),
  Table('tasks', [
    Column.text('user_id'),
    Column.text('title'),
    Column.text('project_id'),
    Column.text('goal_id'),
    Column.text('due_date'),
    Column.text('priority'),
    Column.text('status'),
    Column.text('completed_at'),
    Column.text('notes'),
    Column.text('created_at'),
    Column.text('updated_at'),
    Column.text('deleted_at'),
  ]),
  Table('habits', [
    Column.text('user_id'),
    Column.text('name'),
    Column.text('life_area_id'),
    Column.text('usual_time'),
    Column.text('days'),
    Column.text('created_at'),
    Column.text('updated_at'),
    Column.text('deleted_at'),
  ]),
  Table('habit_logs', [
    Column.text('user_id'),
    Column.text('habit_id'),
    Column.text('day'),
    Column.text('status'),
    Column.text('created_at'),
    Column.text('updated_at'),
    Column.text('deleted_at'),
  ]),
  Table('focus_sessions', [
    Column.text('user_id'),
    Column.text('task_id'),
    Column.text('started_at'),
    Column.text('ended_at'),
    Column.integer('focus_seconds'),
    Column.text('created_at'),
    Column.text('updated_at'),
    Column.text('deleted_at'),
  ]),
  Table('sleep_logs', [
    Column.text('user_id'),
    Column.text('day'),
    Column.text('bed_time'),
    Column.text('wake_time'),
    Column.text('rested'),
    Column.text('note'),
    Column.text('created_at'),
    Column.text('updated_at'),
    Column.text('deleted_at'),
  ]),
  Table('inbox_items', [
    Column.text('user_id'),
    Column.text('text'),
    Column.text('kind'),
    Column.text('created_at'),
    Column.text('updated_at'),
    Column.text('deleted_at'),
  ]),
  Table('preferences', [
    Column.text('user_id'),
    Column.text('today_sections'),
    Column.text('created_at'),
    Column.text('updated_at'),
    Column.text('deleted_at'),
  ]),
  // Kept on this device only: the focus timer that is running now.
  Table.localOnly('focus_timer', [
    Column.text('user_id'),
    Column.text('task_id'),
    Column.text('started_at'),
    Column.text('running_since'),
    Column.integer('worked_ms'),
    Column.integer('target_minutes'),
  ]),
]);
